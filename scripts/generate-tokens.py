#!/usr/bin/env python3
"""Generate native tokens from the same global CSS variables used by Tailwind.

No third-party Python packages. Run with --check in CI to detect stale output.
"""
import argparse
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'Design/tokens.css'
OUTPUT = ROOT / 'Sources/Senda/DesignTokens.generated.swift'


def identifier(name):
    parts = name.split('-')
    return parts[0] + ''.join(part.title() for part in parts[1:])


def color(value):
    numbers = [float(n) for n in re.findall(r'[\d.]+', value)]
    lightness, chroma, hue = numbers[:3]
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    linear = (4.0767416621*l - 3.3077115913*m + 0.2309699292*s,
              -1.2684380046*l + 2.6097574011*m - 0.3413193965*s,
              -0.0041960863*l - 0.7034186147*m + 1.7076147010*s)
    def gamma(c):
        c = max(0, min(1, c))
        return 12.92*c if c <= 0.0031308 else 1.055*c**(1/2.4)-0.055
    r, g, b = map(gamma, linear)
    alpha = numbers[3] if len(numbers) > 3 else 1
    return f'NSColor(srgbRed: {r:.8f}, green: {g:.8f}, blue: {b:.8f}, alpha: {alpha:g})'


def generate():
    css = SOURCE.read_text()
    def palette(selector):
        block = re.search(re.escape(selector) + r'\s*\{([^}]+)\}', css).group(1)
        return dict(re.findall(r'--([\w-]+):\s*(oklch\([^)]+\))', block))
    light, dark = palette(':root'), palette('.dark')
    lines = ['// Generated by scripts/generate-tokens.py from Design/tokens.css. Do not edit.',
             '// Beautiful UI © 2026 Shane Levine, MIT; see THIRD_PARTY_NOTICES.md.',
             'import AppKit', 'import SwiftUI', '', 'enum SendaTokens {']
    for name, value in light.items():
        key = identifier(name)
        lines += [f'    static let {key}NS = adaptive(light: {color(value)},',
                  f'                                     dark: {color(dark.get(name, value))})',
                  f'    static let {key} = Color(nsColor: {key}NS)']
    for name, value in re.findall(r'--((?:radius-[\w-]+|spacing)):\s*([\d.]+)px;', css):
        lines.append(f'    static let {identifier(name)}: CGFloat = {value}')
    lines += ['    static func space(_ units: CGFloat) -> CGFloat { spacing * units }',
              '    private static func adaptive(light: NSColor, dark: NSColor) -> NSColor {',
              '        NSColor(name: nil) { $0.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? dark : light }',
              '    }', '}', '', 'typealias T = SendaTokens', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true')
    args = parser.parse_args(); result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != result:
            raise SystemExit('Native tokens are stale. Run python3 scripts/generate-tokens.py')
        print('Design tokens match CSS.')
    else:
        OUTPUT.write_text(result)
